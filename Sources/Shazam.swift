import Fingerprint
import Foundation

enum ShazamRecognitionError: LocalizedError {
    case invalidWindow
    case fingerprintFailed
    case httpStatus(Int)
    case invalidResponse

    var errorDescription: String? {
        switch self {
        case .invalidWindow: "Recognition needs a 12-second audio window."
        case .fingerprintFailed: "Could not generate an audio fingerprint."
        case .httpStatus(let code): "Shazam lookup returned HTTP \(code)."
        case .invalidResponse: "Shazam lookup returned an unexpected response."
        }
    }
}

struct ShazamRecognizer: Sendable {
    private let session: URLSession
    private let durations = TrackDurations()

    init(session: URLSession = .shared) {
        self.session = session
    }

    func recognize(_ samples: [Int16]) async throws -> RecognizedTrack? {
        guard samples.count == 192_000 else { throw ShazamRecognitionError.invalidWindow }
        try Task.checkCancellation()
        let signature = try await Task.detached(priority: .utility) {
            try Self.fingerprint(samples)
        }.value
        try Task.checkCancellation()

        let (data, response) = try await session.data(for: Self.request(signature: signature))
        guard let http = response as? HTTPURLResponse else { throw ShazamRecognitionError.invalidResponse }
        guard (200..<300).contains(http.statusCode) else { throw ShazamRecognitionError.httpStatus(http.statusCode) }
        guard let result = try? JSONDecoder().decode(LookupResponse.self, from: data) else {
            throw ShazamRecognitionError.invalidResponse
        }
        guard !result.matches.isEmpty else { return nil }
        guard let track = result.track,
              !track.key.isEmpty, !track.title.isEmpty, !track.subtitle.isEmpty else {
            throw ShazamRecognitionError.invalidResponse
        }

        let duration = await durations.duration(for: track, session: session)
        try Task.checkCancellation()
        return RecognizedTrack(key: track.key, artist: track.subtitle, title: track.title, durationSeconds: duration)
    }

    private static func fingerprint(_ samples: [Int16]) throws -> String {
        let bytes = samples.withUnsafeBufferPointer { buffer in
            scrobbler_fingerprint(buffer.baseAddress, buffer.count)
        }
        guard let data = bytes.data, bytes.length > 0 else { throw ShazamRecognitionError.fingerprintFailed }
        defer { scrobbler_free_fingerprint(bytes) }
        return "data:audio/vnd.shazam.sig;base64," + Data(bytes: data, count: bytes.length).base64EncodedString()
    }

    // ShazamIO's discovery/v5 request, with the fingerprint generated by our native bridge.
    private static func request(signature: String) throws -> URLRequest {
        let path = "https://amp.shazam.com/discovery/v5/en-US/GB/iphone/-/tag/\(UUID().uuidString)/\(UUID().uuidString)"
        let query = "sync=true&webv3=true&sampling=true&connected=&shazamapiversion=v3&sharehub=true&hubv5minorversion=v5.1&hidelb=true&video=v3"
        guard let url = URL(string: "\(path)?\(query)") else { throw ShazamRecognitionError.invalidResponse }
        let body = LookupBody(
            timezone: TimeZone.current.identifier,
            signature: .init(uri: signature, samplems: 12_000),
            timestamp: Int64(Date().timeIntervalSince1970 * 1_000)
        )
        var request = URLRequest(url: url, cachePolicy: .reloadIgnoringLocalCacheData, timeoutInterval: 12)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.setValue("*/*", forHTTPHeaderField: "Accept")
        request.setValue("en-US", forHTTPHeaderField: "Accept-Language")
        request.setValue("IPHONE", forHTTPHeaderField: "X-Shazam-Platform")
        request.setValue("14.1.0", forHTTPHeaderField: "X-Shazam-AppVersion")
        request.setValue("Dalvik/2.1.0 (Linux; U; Android 5.0.2; VS980 4G Build/LRX22G)", forHTTPHeaderField: "User-Agent")
        request.httpBody = try JSONEncoder().encode(body)
        return request
    }
}

private struct LookupBody: Encodable {
    struct Signature: Encodable {
        let uri: String
        let samplems: Int
    }

    let timezone: String
    let signature: Signature
    let timestamp: Int64
    let context: [String: String] = [:]
    let geolocation: [String: String] = [:]
}

private struct LookupResponse: Decodable {
    struct Match: Decodable {
        let id: String?
    }

    struct Track: Decodable, Sendable {
        struct Hub: Decodable, Sendable {
            struct Action: Decodable, Sendable {
                let type: String?
                let id: String?
            }

            let actions: [Action]?
        }

        let key: String
        let title: String
        let subtitle: String
        let hub: Hub?
    }

    let matches: [Match]
    let track: Track?
}

private actor TrackDurations {
    private struct Storefront: Decodable {
        struct Track: Decodable {
            let trackId: Int64?
            let trackName: String?
            let artistName: String?
            let trackTimeMillis: Int?
        }

        let results: [Track]
    }

    private var durations: [String: Double] = [:]
    private var unavailableUntil: [String: Date] = [:]

    func duration(for track: LookupResponse.Track, session: URLSession) async -> Double? {
        if let seconds = durations[track.key] { return seconds }
        if let until = unavailableUntil[track.key], until > Date() { return nil }
        guard let rawID = track.hub?.actions?.first(where: { $0.type == "applemusicplay" })?.id,
              let id = Int64(rawID), id > 0,
              var components = URLComponents(string: "https://itunes.apple.com/lookup") else { return nil }
        components.queryItems = [URLQueryItem(name: "id", value: String(id)), URLQueryItem(name: "country", value: "GB")]
        guard let url = components.url else { return nil }

        // Optional metadata should not suppress a valid recognition. Back off briefly on lookup failures.
        let request = URLRequest(url: url, timeoutInterval: 4)
        if let (data, response) = try? await session.data(for: request),
           let http = response as? HTTPURLResponse, (200..<300).contains(http.statusCode),
           let storefront = try? JSONDecoder().decode(Storefront.self, from: data),
           let match = storefront.results.first(where: { $0.trackId == id }),
           let title = match.trackName, let artist = match.artistName,
           title.caseInsensitiveCompare(track.title) == .orderedSame,
           artist.caseInsensitiveCompare(track.subtitle) == .orderedSame,
           let milliseconds = match.trackTimeMillis, milliseconds > 0 {
            let seconds = Double(milliseconds) / 1_000
            durations[track.key] = seconds
            unavailableUntil[track.key] = nil
            return seconds
        }
        unavailableUntil[track.key] = Date().addingTimeInterval(60)
        return nil
    }
}
